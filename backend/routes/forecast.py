from fastapi import APIRouter, HTTPException
import pandas as pd
import os

from ml.preprocessing import get_active_dataset_path, get_dataset_metadata
from ml.forecasting import generate_sales_forecast

router = APIRouter(
    prefix="/forecast",
    tags=["Forecast"]
)


def load_forecast_data():
    path = get_active_dataset_path()
    if not os.path.exists(path):
        raise HTTPException(
            status_code=404,
            detail=f"Dataset not found at: {path}"
        )
    try:
        df = pd.read_csv(path)
    except Exception as e:
        raise HTTPException(
            status_code=500,
            detail=f"Unable to read dataset for forecasting: {str(e)}"
        )
    if df.empty:
        raise HTTPException(
            status_code=400,
            detail="The dataset is empty. Cannot generate forecast."
        )
    return df


@router.get("")
@router.get("/")
def get_forecast():
    """
    Get sales forecast generated by the ML pipeline for the active dataset.
    """
    df = load_forecast_data()
    try:
        result = generate_sales_forecast(df, periods_ahead=6)
        metadata = get_dataset_metadata()
        result["dataset_name"] = metadata.get("filename", os.path.basename(get_active_dataset_path()))
        return result
    except ValueError as ve:
        raise HTTPException(status_code=400, detail=str(ve))
    except Exception as e:
        raise HTTPException(
            status_code=500,
            detail=f"Forecasting engine error: {str(e)}"
        )


@router.post("/run")
def run_forecast():
    """
    Trigger or refresh forecasting execution for the active dataset.
    """
    return get_forecast()

